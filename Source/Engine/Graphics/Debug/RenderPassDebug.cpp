static const uint32_t Debug_vert[1828];
static const uint32_t Debug_frag[568];

#define MAX_VERTEX_COUNT 6144

DebugRenderPass::DebugRenderPass(Extent2D extent, VulkanDevice* device, Renderer* renderer, VkImageView colorView, VkImageView depthView)
    : _colorView(colorView)
    , _depthView(depthView)
    , _extent(extent)
{

    VulkanShader vertexShader{device, std::span(Debug_vert)};
    VulkanShader fragmentShader{device, std::span(Debug_frag)};

    // Create the debug pipeline.
    VulkanPipelineStateInfo state;
    state.stages.shaders = { &vertexShader, &fragmentShader };

    state.vertexState.inputAttribs = {
        {0, 0, VK_FORMAT_R32G32B32_SFLOAT, offsetof(DebugVertex, position)},
        {1, 0, VK_FORMAT_R32G32B32_SFLOAT, offsetof(DebugVertex, color)},
        {2, 0, VK_FORMAT_R32_SFLOAT, offsetof(DebugVertex, width)}
    };

    state.vertexState.inputBindings = {
        {0, sizeof(DebugVertex), VK_VERTEX_INPUT_RATE_VERTEX}
    };

    state.dynamicStates.push_back(VK_DYNAMIC_STATE_PRIMITIVE_TOPOLOGY);
    state.dynamicStates.push_back(VK_DYNAMIC_STATE_LINE_WIDTH);

    _debugPipeline = std::make_unique<VulkanPipeline>(device, renderer, state, 1);

    _lines.resize(MAX_VERTEX_COUNT/3);
    _triangles.resize(MAX_VERTEX_COUNT/3);
    _points.resize(MAX_VERTEX_COUNT/3);
    _vertices.resize(MAX_VERTEX_COUNT);

}

DebugRenderPass::~DebugRenderPass()
{
}

void DebugRenderPass::Record(RenderData& rd)
{
    auto cmd = rd.GetCommandBuffer();

    // Setup the render pass for dynamic rendering.
    VkRenderingAttachmentInfo colorAttachment = {};
    colorAttachment.sType = VK_STRUCTURE_TYPE_RENDERING_ATTACHMENT_INFO;
    colorAttachment.pNext = nullptr;
    colorAttachment.imageView = _colorView;
    colorAttachment.imageLayout = VK_IMAGE_LAYOUT_COLOR_ATTACHMENT_OPTIMAL;
    colorAttachment.resolveMode = VK_RESOLVE_MODE_NONE;
    colorAttachment.resolveImageView = VK_NULL_HANDLE;
    colorAttachment.resolveImageLayout = VK_IMAGE_LAYOUT_UNDEFINED;
    colorAttachment.loadOp = VK_ATTACHMENT_LOAD_OP_LOAD;
    colorAttachment.storeOp = VK_ATTACHMENT_STORE_OP_STORE;
    colorAttachment.clearValue = {};

    // When using a higher sample count, the image must be resolved from the sampled image.
    if (rd.GetSampleCount() != VK_SAMPLE_COUNT_1_BIT) {
        colorAttachment.resolveMode = VK_RESOLVE_MODE_AVERAGE_BIT;
        colorAttachment.resolveImageLayout = VK_IMAGE_LAYOUT_COLOR_ATTACHMENT_OPTIMAL;
        colorAttachment.resolveImageView = rd.GetSwapchainImageView();
    } else {
        colorAttachment.imageView = rd.GetSwapchainImageView();
    }

    VkRenderingAttachmentInfo depthAttachment = {};
    depthAttachment.sType = VK_STRUCTURE_TYPE_RENDERING_ATTACHMENT_INFO;
    depthAttachment.pNext = nullptr;
    depthAttachment.imageView = _depthView;
    depthAttachment.imageLayout = VK_IMAGE_LAYOUT_DEPTH_ATTACHMENT_OPTIMAL;
    depthAttachment.resolveMode = VK_RESOLVE_MODE_NONE;
    depthAttachment.resolveImageView = VK_NULL_HANDLE;
    depthAttachment.resolveImageLayout = VK_IMAGE_LAYOUT_UNDEFINED;
    depthAttachment.loadOp = VK_ATTACHMENT_LOAD_OP_LOAD;
    depthAttachment.storeOp = VK_ATTACHMENT_STORE_OP_DONT_CARE;
    depthAttachment.clearValue = {};

    VkRect2D renderArea = {};
    renderArea.offset = { 0, 0 };
    renderArea.extent = VkExtent2D{_extent.width, _extent.height};

    VkRenderingInfo renderingInfo = {};
    renderingInfo.sType = VK_STRUCTURE_TYPE_RENDERING_INFO;
    renderingInfo.pNext = nullptr;
    renderingInfo.flags = 0;
    renderingInfo.renderArea = renderArea;
    renderingInfo.layerCount = 1;
    renderingInfo.viewMask = 0;
    renderingInfo.colorAttachmentCount = 1;
    renderingInfo.pColorAttachments = &colorAttachment;
    renderingInfo.pDepthAttachment = &depthAttachment;
    renderingInfo.pStencilAttachment = nullptr;

    vkCmdBeginRendering(cmd, &renderingInfo);




    vkCmdEndRendering(cmd);
}

